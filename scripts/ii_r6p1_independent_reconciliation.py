def oracle_fifo(case: dict) -> dict:
    lots = []
    for a in case["acquisitions"]:
        lots.append({"acquisitionDate": a["acquisitionDate"], "remaining": a["units"], "costPerUnit": a["costPerUnit"]})
    lots.sort(key=lambda l: l["acquisitionDate"])

    result_by_disposal = {}
    for disp in case["disposals"]:
        remaining_to_consume = disp["units"]
        consumed = []
        for lot in lots:
            if remaining_to_consume <= 1e-9:
                break
            if lot["remaining"] <= 1e-9:
                continue
            take = min(lot["remaining"], remaining_to_consume)
            lot["remaining"] -= take
            consumed.append({
                "acquisitionDate": lot["acquisitionDate"],
                "unitsConsumed": round(take, 6),
                "costBasis": round(take * lot["costPerUnit"], 2),
            })
            remaining_to_consume -= take
        if remaining_to_consume > 1e-6:
            raise ValueError(f"{case['id']}: disposal exceeds available lot balance by {remaining_to_consume}")
        total_cost_basis = round(sum(c["costBasis"] for c in consumed), 2)
        total_units = round(sum(c["unitsConsumed"] for c in consumed), 6)
        result_by_disposal[disp["sourceEventId"]] = {
            "consumedLots": consumed,
            "totalCostBasis": total_cost_basis,
            "totalUnitsConsumed": total_units,
        }
    return {"byDisposal": result_by_disposal}


def oracle_grandfathering(case: dict) -> dict:
    actual = case["actualCostPerUnit"]
    sale = case["salePricePerUnit"]
    fmv = case["fmvPerUnit"]
    acq = case["acquisitionDate"]

    if not case.get("isEquityOriented", True):
        return {"basisSource": "not_applicable", "costBasisPerUnit": round(actual, 6)}
    if acq >= "2018-02-01":
        return {"basisSource": "not_applicable", "costBasisPerUnit": round(actual, 6)}
    if fmv is None:
        return {"basisSource": "fmv_unavailable", "costBasisPerUnit": round(actual, 6)}

    # THE FORMULA: max(actualCost, min(fmv, salePrice)).
    lower_of_fmv_and_sale = min(fmv, sale)
    cost_basis = max(actual, lower_of_fmv_and_sale)
    basis_source = "fmv_grandfathered" if cost_basis > actual else "actual_cost"
    return {"basisSource": basis_source, "costBasisPerUnit": round(cost_basis, 6)}


def oracle_boundary(case: dict) -> dict:
    acq = case["acquisitionDate"]
    disp = case["disposalDate"]
    months = case["thresholdMonths"]
    anniversary = add_months_clamped(acq, months)
    is_long_term = disp > anniversary  # strictly after
    return {
        "isLongTerm": is_long_term,
        "holdingDays": holding_days(acq, disp),
        "anniversaryDate": anniversary,
    }


SPECIFIED_FUND_CUTOFF = "2023-04-01"  # Section 50AA / Finance Act 2023
BUDGET_2024_BOUNDARY = "2024-07-23"  # Finance (No. 2) Act, 2024


def oracle_debt(case: dict) -> dict:
    """Covers BOTH the 'debt' family (all fixtures acquired on/after the
    Section 50AA cutoff -> always STCG, unchanged R6-P1 behaviour) and the
    'debt_pre2023' family (R6-DEBTFIX, 2026-08-22: fixtures acquired BEFORE
    the cutoff -> legacy debt-fund treatment, keyed by the DISPOSAL date's
    own rule window, per ruleVersions.ts's LegacyDebtFundRegime / the
    R6_TAX_LEGAL_SOURCE_REGISTER.md Section 4a research)."""
    acq = case["acquisitionDate"]
    disp = case["disposalDate"]
    units = case["unitsConsumed"]
    cost_basis = round(units * case["costPerUnit"], 2)
    sale_value = round(units * case["salePricePerUnit"], 2)
    taxable_gain = round(sale_value - cost_basis, 2)  # never indexed, either branch

    if acq >= SPECIFIED_FUND_CUTOFF:
        # Section 50AA: always short-term, regardless of holding period.
        return {
            "gainType": "stcg",
            "holdingDays": holding_days(acq, disp),
            "costBasisUsed": cost_basis,
            "saleValue": sale_value,
            "taxableGain": taxable_gain,
        }

    # Acquired before the cutoff: legacy regime, threshold/rate depends on
    # which side of the 23-Jul-2024 Budget boundary the DISPOSAL falls.
    threshold_months = 36 if disp < BUDGET_2024_BOUNDARY else 24
    anniversary = add_months_clamped(acq, threshold_months)
    is_long_term = disp > anniversary
    gain_type = "ltcg" if is_long_term else "stcg"
    return {
        "gainType": gain_type,
        "holdingDays": holding_days(acq, disp),
        "costBasisUsed": cost_basis,
        "saleValue": sale_value,
        "taxableGain": taxable_gain,
    }


def oracle_fy_aggregation(case: dict) -> dict:
    by_fy = {}
    for d in case["disposals"]:
        fy = financial_year_of(d["disposalDate"])
        by_fy.setdefault(fy, []).append(d)

    out = {}
    for fy, disposals in by_fy.items():
        fy_end = financial_year_end(fy)
        rule = resolve_rule_version(fy_end)
        exemption_threshold = rule["ltcg_exemption_inr"]
        total = round(sum(d["taxableGain"] for d in disposals), 2)
        exemption_applied = round(min(max(total, 0), exemption_threshold), 2)
        taxable_after = round(max(total - exemption_applied, 0), 2)
        out[fy] = {
            "exemptionThresholdInr": exemption_threshold,
            "exemptionRuleVersion": rule["version"],
            "totalLtcgBeforeExemption": total,
            "exemptionApplied": exemption_applied,
            "taxableLtcgAfterExemption": taxable_after,
            "contributingDisposalCount": len(disposals),
        }
    return {"byFinancialYear": out}


def oracle_exit_load(case: dict) -> dict:
    acq = case["acquisitionDate"]
    disp = case["disposalDate"]
    hd = holding_days(acq, disp)
    tiers = sorted(case["tiers"], key=lambda t: t["uptoDays"])
    load_pct = 0
    for t in tiers:
        if hd <= t["uptoDays"]:
            load_pct = t["loadPct"]
            break
    amount = round(case["saleValueApportioned"] * load_pct / 100, 2)
    return {"holdingDays": hd, "applicableLoadPct": load_pct, "exitLoadAmount": amount}


def oracle_ambiguous(case: dict) -> dict:
    return {"gainType": "unresolved", "taxableGain": None}


def oracle_rate_version(case: dict) -> dict:
    rule = resolve_rule_version(case["disposalDate"])
    return {
        "ruleVersion": rule["version"],
        "placeholder": rule["placeholder"],
        "stcgRatePct": rule["stcg_rate_pct"],
        "ltcgRatePct": rule["ltcg_rate_pct"],
        "ltcgExemptionThresholdInr": rule["ltcg_exemption_inr"],
    }


def oracle_act_transition(case: dict) -> dict:
    # R6-FINAL closure, Section 10: full disposal-tax computation (rule
    # version + holding-period STCG/LTCG split + grandfathering-if-applicable)
    # for a disposal dated either side of the 1961 Act -> 2025 Act boundary.
    acq = case["acquisitionDate"]
    disp = case["disposalDate"]
    units = case["unitsConsumed"]
    cost_per_unit = case["costPerUnit"]
    sale_per_unit = case["salePricePerUnit"]
    sale_value = round(units * sale_per_unit, 2)
    cost_basis = round(units * cost_per_unit, 2)

    rule = resolve_rule_version(disp)
    anniversary = add_months_clamped(acq, 12)
    is_long_term = disp > anniversary
    gain_type = "ltcg" if is_long_term else "stcg"
    # All ACTTRANS fixtures acquire on/after 2018-02-01 (post grandfathering
    # cutoff), so grandfathering never applies here — cost basis is plain.
    taxable_gain = round(sale_value - cost_basis, 2)

    return {
        "ruleVersion": rule["version"],
        "placeholder": rule["placeholder"],
        "gainType": gain_type,
        "costBasisUsed": cost_basis,
        "saleValue": sale_value,
        "taxableGain": taxable_gain,
    }


def oracle_grand_boundary(case: dict) -> dict:
    # R6-FINAL closure, Section 11: full disposal-tax computation straddling
    # the 31-Jan/1-Feb-2018 grandfathering eligibility cutoff, disposed under
    # the 2025 Act (disposalDate 2026-06-15) to also exercise continuity.
    acq = case["acquisitionDate"]
    disp = case["disposalDate"]
    units = case["unitsConsumed"]
    cost_per_unit = case["costPerUnit"]
    fmv = case["fmvPerUnit"]
    sale_per_unit = case["salePricePerUnit"]
    sale_value = round(units * sale_per_unit, 2)

    rule = resolve_rule_version(disp)
    # All fixtures here are long-term by construction (2018 acquisition,
    # 2026 disposal) — no need to re-derive the STCG/LTCG split.
    eligible = acq < "2018-02-01"
    if eligible:
        lower_of_fmv_and_sale = min(fmv, sale_per_unit)
        basis_per_unit = max(cost_per_unit, lower_of_fmv_and_sale)
        basis_source = "fmv_grandfathered" if basis_per_unit > cost_per_unit else "actual_cost"
    else:
        basis_per_unit = cost_per_unit
        basis_source = "not_applicable"
    cost_basis = round(units * basis_per_unit, 2)
    taxable_gain = round(sale_value - cost_basis, 2)

    return {
        "ruleVersion": rule["version"],
        "grandfatheringEligible": eligible,
        "basisSource": basis_source,
        "costBasisUsed": cost_basis,
        "saleValue": sale_value,
        "taxableGain": taxable_gain,
    }


FAMILY_ORACLES = {
    "fifo": oracle_fifo,
    "grandfathering": oracle_grandfathering,
    "boundary": oracle_boundary,
    "debt": oracle_debt,
    "debt_pre2023": oracle_debt,
    "fy_aggregation": oracle_fy_aggregation,
    "cross_fy": oracle_fy_aggregation,  # same aggregation logic, different fixture emphasis
    "exit_load": oracle_exit_load,
    "ambiguous": oracle_ambiguous,
    "rate_version": oracle_rate_version,
    "act_transition": oracle_act_transition,
    "grand_boundary": oracle_grand_boundary,
}


def main() -> int:
    if not CASES_PATH.exists():
        print(f"cases.json not found at {CASES_PATH} — run generate_cases.mjs first.", file=sys.stderr)
        return 1

    data = json.loads(CASES_PATH.read_text(encoding="utf-8"))
    cases = data["cases"]

    results = {}
    counts = {}
    for case in cases:
        fam = case["family"]
        oracle = FAMILY_ORACLES.get(fam)
        if oracle is None:
            raise ValueError(f"No oracle registered for family {fam}")
        results[case["id"]] = oracle(case)
        counts[fam] = counts.get(fam, 0) + 1

    # newline='' prevents Python's universal-newline translation from turning
    # json.dumps's '\n' line separators into CRLF on Windows — this repo's
    # convention (and a prior CRLF-broke-an-exact-match-test incident) requires LF.
    RESULTS_PATH.write_text(json.dumps({"cases": results}, indent=2, sort_keys=True), encoding="utf-8", newline="")
    print(f"Computed {len(results)} oracle results -> {RESULTS_PATH}")
    print("By family:", counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
