def parse_iso(d: str) -> date:
    y, m, dd = (int(x) for x in d.split("-"))
    return date(y, m, dd)


def iso(d: date) -> str:
    return d.isoformat()


def days_in_month(year: int, month: int) -> int:
    if month == 12:
        return (date(year + 1, 1, 1) - date(year, 12, 1)).days
    return (date(year, month + 1, 1) - date(year, month, 1)).days


def add_months_clamped(iso_date: str, months: int) -> str:
    d = parse_iso(iso_date)
    total_month_index0 = (d.month - 1) + months
    target_year = d.year + total_month_index0 // 12
    target_month0 = total_month_index0 % 12  # Python % always non-negative for positive divisor
    target_month = target_month0 + 1
    clamped_day = min(d.day, days_in_month(target_year, target_month))
    return iso(date(target_year, target_month, clamped_day))


def add_days(iso_date: str, n: int) -> str:
    return iso(parse_iso(iso_date) + timedelta(days=n))


def holding_days(acq: str, disp: str) -> int:
    return (parse_iso(disp) - parse_iso(acq)).days


