def resolve_rule_version(disposal_date: str) -> dict:
    for v in RULE_VERSIONS:
        if disposal_date >= v["effective_from"] and (v["effective_to"] is None or disposal_date <= v["effective_to"]):
            return v
    raise ValueError(f"No rule version covers {disposal_date}")


def financial_year_of(d: str) -> str:
    dt = parse_iso(d)
    start_year = dt.year if dt.month >= 4 else dt.year - 1
    return f"FY{start_year}-{str((start_year + 1) % 100).zfill(2)}"


def financial_year_end(fy: str) -> str:
    start_year = int(fy[2:6])
    return f"{start_year + 1}-03-31"


