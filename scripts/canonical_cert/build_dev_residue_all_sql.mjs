/**
 * Builds scripts/canonical_cert/dev_residue_ALL_for_PO.sql -- ONE guarded,
 * one-transaction, row-count-asserting DEV cleanup for every row the four
 * stage-3 certifiers could not remove through the service role (the applied
 * card/loan chains the import-bridge guards protect; GP-H1).
 *
 * Sources (each certifier's own PO file, parsed, never retyped):
 *   golden_pair/dev_residue_A_liability_chains.sql      range A
 *   econ/dev_residue_B_liability_chains.sql             range B
 *   scaleui/dev_residue_C_liability_retirement.sql      range C (hand-mirrored below: it restores a fixture row)
 *   secrev/dev_residue_D_liability_chain.sql            range D
 *
 *   node scripts/canonical_cert/build_dev_residue_all_sql.mjs          -> writes the file
 *   node scripts/canonical_cert/build_dev_residue_all_sql.mjs --check  -> exit 1 if the file is stale
 *
 * renderResidueSql(spec) is also used by tests/unit/canonicalCertResidueAllSql.test.ts, which runs the
 * rendered SQL on the real migration chain (PGlite) against synthetic applied chains, including the
 * negative controls (a production policy row, a wrong expected count, a non-synthetic owner).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** Emails of the synthetic fixture users (USER_RANGES.json): FCAST + E2E50. Anything else is refused. */
export const SYNTHETIC_EMAIL_PATTERNS = ['%@example.test', '%@test.fhip.invalid'];

/** Delete order proven on the real migration chain (tests/unit/gpImportChainDeletion.test.ts + the
 *  combined test): applications first (frees liabilities.last_import_application_id), then proposals,
 *  liability statements, facility accounts, liabilities, uploads. */
export const DELETE_ORDER = ['fhip_import_applications', 'fhip_import_proposals', 'fdh_liability_statements', 'fdh_financial_accounts', 'liabilities', 'fdh_statement_uploads'];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const idList = (ids) => ids.map(q).join(', ');

/** Parses a certifier file of `delete from T where [user_id = 'u' and ]id in (...); -- expect N` lines. */
export function parseSimpleResidueFile(text, label) {
  const deletes = [];
  const re = /delete from (\w+) where (?:user_id = '([0-9a-f-]{36})' and )?id in \(([^)]*)\);\s*-- expect (\d+)/g;
  let m;
  while ((m = re.exec(text))) {
    const ids = [...m[3].matchAll(/'([0-9a-f-]{36})'/g)].map((x) => x[1]);
    if (ids.length !== Number(m[4])) throw new Error(`${label}: ${m[1]} lists ${ids.length} ids but expects ${m[4]}`);
    deletes.push({ table: m[1], userId: m[2] ?? null, ids });
  }
  if (deletes.length === 0) throw new Error(`${label}: no delete lines parsed`);
  return deletes;
}

/**
 * spec = { title, sections: [{ label, preUpdates?: [{ table, id, userId, set, expect }], deletes: [{ table, userId, ids }] }] }
 * Emits: DEV guard -> ownership/presence pre-check of EVERY targeted row -> updates -> deletes (DELETE_ORDER),
 * each with an asserted row count, all inside ONE transaction (any exception rolls everything back).
 */
export function renderResidueSql(spec) {
  const lines = [];
  const L = (s = '') => lines.push(s);
  const emailOk = (alias) => `(${SYNTHETIC_EMAIL_PATTERNS.map((p) => `${alias}.email like ${q(p)}`).join(' or ')})`;
  let total = 0;
  for (const s of spec.sections) for (const d of s.deletes) total += d.ids.length;
  const updates = spec.sections.reduce((n, s) => n + (s.preUpdates?.length ?? 0), 0);

  L(`-- ${spec.title}`);
  L('-- GENERATED by scripts/canonical_cert/build_dev_residue_all_sql.mjs -- do not hand-edit; re-run the builder.');
  L('--');
  L('-- DEV ONLY (vqycarelcoijzwlpkpcz). Paste the WHOLE file into the DEV Supabase SQL editor and run it once.');
  L(`-- It deletes ${total} rows and restores ${updates} fixture row(s), all created/changed by the stage-3 certifiers,`);
  L('-- in ONE transaction. It REFUSES (raises, nothing changes) unless:');
  L("--   * ii_nav_retention_policy has an environment='dev' row and NO environment='production' row;");
  L('--   * every targeted row exists and belongs to a synthetic fixture user (email @example.test / @test.fhip.invalid);');
  L('--   * every UPDATE / DELETE touches exactly the expected number of rows.');
  L('-- Expected result: NOTICE "canonical-cert residue removed: ..." and COMMIT. Any ERROR means nothing was changed.');
  for (const s of spec.sections) {
    const byTable = {};
    for (const d of s.deletes) byTable[d.table] = (byTable[d.table] ?? 0) + d.ids.length;
    L(`--   ${s.label}: ${Object.entries(byTable).map(([t, n]) => `${t} ${n}`).join(', ')}${s.preUpdates?.length ? `; restores ${s.preUpdates.length} fixture row(s)` : ''}`);
  }
  L();
  L('begin;');
  L();
  L('-- The applied-chain rows are guarded by the import-bridge triggers; this transaction-local setting is the');
  L('-- documented internal-write path (the same one every SECURITY DEFINER Apply uses). It ends with the transaction.');
  L("select set_config('fhip.import_bridge_internal_write', 'true', true);");
  L();
  L('do $$');
  L('declare');
  L('  n int;');
  L('begin');
  L('  -- 0. Environment guard.');
  L("  if not exists (select 1 from ii_nav_retention_policy where environment = 'dev') then");
  L("    raise exception 'REFUSED: no dev row in ii_nav_retention_policy -- this is not the DEV database';");
  L('  end if;');
  L("  if exists (select 1 from ii_nav_retention_policy where environment = 'production') then");
  L("    raise exception 'REFUSED: ii_nav_retention_policy has a production row -- this is PRODUCTION';");
  L('  end if;');
  L();
  L('  -- 1. Every targeted row must exist and belong to a synthetic fixture user (checked BEFORE any change).');
  for (const s of spec.sections) {
    for (const u of s.preUpdates ?? []) {
      L(`  select count(*) into n from ${u.table} t join auth.users u on u.id = t.user_id where t.id = ${q(u.id)} and t.user_id = ${q(u.userId)} and ${emailOk('u')};`);
      L(`  if n <> 1 then raise exception 'REFUSED (${s.label}): ${u.table} ${u.id} -- % synthetic-owned rows (expected 1)', n; end if;`);
    }
    for (const d of s.deletes) {
      const userClause = d.userId ? ` and t.user_id = ${q(d.userId)}` : '';
      L(`  select count(*) into n from ${d.table} t join auth.users u on u.id = t.user_id where t.id in (${idList(d.ids)})${userClause} and ${emailOk('u')};`);
      L(`  if n <> ${d.ids.length} then raise exception 'REFUSED (${s.label}): ${d.table} -- % synthetic-owned rows present (expected ${d.ids.length})', n; end if;`);
    }
  }
  L();
  L('  -- 2. Restore fixture rows the certifiers changed (before the deletes free their links).');
  for (const s of spec.sections) {
    for (const u of s.preUpdates ?? []) {
      L(`  update ${u.table} set ${u.set} where id = ${q(u.id)} and user_id = ${q(u.userId)};`);
      L(`  get diagnostics n = row_count; if n <> ${u.expect} then raise exception '${s.label}: update ${u.table} ${u.id}: % rows (expected ${u.expect})', n; end if;`);
    }
  }
  L();
  L(`  -- 3. Deletes, one table at a time across all ranges, in the proven order: ${DELETE_ORDER.join(' -> ')}.`);
  for (const table of DELETE_ORDER) {
    for (const s of spec.sections) {
      for (const d of s.deletes.filter((x) => x.table === table)) {
        const userClause = d.userId ? `user_id = ${q(d.userId)} and ` : '';
        L(`  delete from ${table} where ${userClause}id in (${idList(d.ids)});`);
        L(`  get diagnostics n = row_count; if n <> ${d.ids.length} then raise exception '${s.label}: delete ${table}: % rows (expected ${d.ids.length})', n; end if;`);
      }
    }
  }
  const unknown = spec.sections.flatMap((s) => s.deletes.map((d) => d.table)).filter((t) => !DELETE_ORDER.includes(t));
  if (unknown.length) throw new Error(`tables outside DELETE_ORDER: ${[...new Set(unknown)].join(', ')}`);
  L();
  L(`  raise notice 'canonical-cert residue removed: % rows deleted, % fixture row(s) restored', ${total}, ${updates};`);
  L('end $$;');
  L();
  L('commit;');
  L();
  L('-- Afterwards (optional, read-only): every count below must be 0.');
  for (const table of DELETE_ORDER) {
    const ids = spec.sections.flatMap((s) => s.deletes.filter((d) => d.table === table).flatMap((d) => d.ids));
    if (ids.length) L(`select ${q(table)} as table_name, count(*) as remaining from ${table} where id in (${idList(ids)});`);
  }
  return `${lines.join('\n')}\n`;
}

