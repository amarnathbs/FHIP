export function buildSpec() {
  const read = (rel) => fs.readFileSync(path.join(HERE, rel), 'utf8');
  const cText = read('scaleui/dev_residue_C_liability_retirement.sql');
  const c = rangeC();
  // The hand-mirrored range C must agree with the certifier's own file id-for-id.
  for (const id of [...c.preUpdates.map((x) => x.id), ...c.deletes.flatMap((d) => d.ids)]) {
    if (!cText.includes(id)) throw new Error(`range C mirror: ${id} not in scaleui/dev_residue_C_liability_retirement.sql`);
  }
  return {
    title: 'Canonical upload programme, stage 3 -- COMBINED DEV residue cleanup for the PO (ranges A-D)',
    sections: [
      { label: 'range A (golden pair)', deletes: parseSimpleResidueFile(read('golden_pair/dev_residue_A_liability_chains.sql'), 'A') },
      { label: 'range B (economic oracles)', deletes: parseSimpleResidueFile(read('econ/dev_residue_B_liability_chains.sql'), 'B') },
      c,
      { label: 'range D (security review)', deletes: parseSimpleResidueFile(read('secrev/dev_residue_D_liability_chain.sql'), 'D') },
      consolidationRecheck(),
    ],
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = path.join(HERE, 'dev_residue_ALL_for_PO.sql');
  const sql = renderResidueSql(buildSpec());
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== sql) { console.error('dev_residue_ALL_for_PO.sql is stale: re-run the builder'); process.exit(1); }
    console.log('dev_residue_ALL_for_PO.sql is current');
  } else {
    fs.writeFileSync(out, sql, 'utf8'); // UTF-8 without BOM (the Supabase SQL editor rejects a BOM)
    console.log(`wrote ${out}`);
  }
}
